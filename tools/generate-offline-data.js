const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const readJson = (filename) => JSON.parse(fs.readFileSync(path.join(root, filename), 'utf8'));
const notesDirectory = path.join(root, 'notes');
const notes = Object.fromEntries(
  fs.readdirSync(notesDirectory)
    .filter((filename) => filename.endsWith('.md'))
    .sort()
    .map((filename) => [`notes/${filename}`, fs.readFileSync(path.join(notesDirectory, filename), 'utf8')])
);

const data = {
  searchIndex: readJson('search_index.json'),
  examDrills: readJson('exam_drills.json'),
  mockExams: readJson('mock_exams.json'),
  notes
};

const output = `/* Generated by tools/generate-offline-data.js. Do not edit manually. */\nwindow.TERRAFORM_OFFLINE_DATA = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(root, 'offline-data.js'), output);
